namespace OnlineCasino.Controllers
{
    using System.Security.Claims;
    using Microsoft.AspNetCore.Mvc;

    using OnlineCasino.Models;

    /// <summary>
    /// Base controller for all API controllers in OnlineCasino.
    /// Provides:
    /// <list type="bullet">
    ///   <item>Unified conversion of <see cref="Result{T}"/> to <see cref="IActionResult"/>.</item>
    ///   <item>Management of the JWT auth cookie (set / clear).</item>
    ///   <item>Extraction of the current userId from JWT claims.</item>
    ///   <item>Hiding of sensitive data (e.g. JWT token) from the response body.</item>
    /// </list>
    /// All derived controllers automatically receive <c>[ApiController]</c> and <c>[Route("api/[controller]")]</c>.
    /// </summary>
    [ApiController]
    [Route("api/[controller]")]
    public abstract class BaseApiController : ControllerBase
    {
        /// <summary>
        /// Converts a <see cref="Result{T}"/> into an appropriate <see cref="IActionResult"/>.
        /// <para>
        /// Behavior:
        /// <list type="bullet">
        ///   <item>If <paramref name="result"/> is <c>null</c> → <c>500 Internal Server Error</c> with a generic error.</item>
        ///   <item>If successful and Data is <c>null</c> → <c>204 No Content</c>.</item>
        ///   <item>If successful and Data is not <c>null</c> → <c>200 OK</c> with Data.</item>
        ///   <item>If failed → the status code from <see cref="ErrorResponse.StatusCode"/> with <see cref="ErrorResponse"/> as the body
        ///         (e.g. <c>400 Bad Request</c>, <c>401 Unauthorized</c>, <c>403 Forbidden</c>, <c>404 Not Found</c>, <c>409 Conflict</c>).</item>
        /// </list>
        /// </para>
        /// </summary>
        /// <typeparam name="T">The type of the payload on success.</typeparam>
        /// <param name="result">The result returned by the service layer.</param>
        /// <returns>A ready <see cref="IActionResult"/> to return from the controller.</returns>
        protected IActionResult AsActionResult<T>(Result<T> result)
        {
            if (result is null)
                return StatusCode(500, new ErrorResponse(500, "Unexpected error."));

            if (result.IsSuccess)
            {
                if (result.Data is null) return NoContent();
                return Ok(result.Data);
            }

            var err = result.Error ?? new ErrorResponse(500, "Unexpected error.");
            return StatusCode(err.StatusCode, err);
        }

        /// <summary>
        /// Writes the JWT access token into an HttpOnly cookie named <c>access_token</c>.
        /// <para>
        /// Cookie settings:
        /// <list type="bullet">
        ///   <item><c>HttpOnly = true</c> – not accessible from JavaScript (XSS protection).</item>
        ///   <item><c>Secure = true</c> – HTTPS only. If you test React Native against an HTTP-only backend (e.g. emulator), this setting will cause the browser/client to ignore the cookie. For development, make it conditional based on the environment.</item>
        ///   <item><c>SameSite = Strict</c> – not sent on cross-site requests (CSRF protection).</item>
        /// </list>
        /// </para>
        /// </summary>
        /// <param name="token">The JWT token generated by <c>IAuthService</c>.</param>
        /// <param name="expires">UTC expiration date of the token.</param>
        protected void SetAuthCookie(string token, DateTime expires)
        {
            Response.Cookies.Append("access_token", token, new CookieOptions
            {
                HttpOnly = true,
                Secure = true,
                SameSite = SameSiteMode.Strict,
                Expires = expires
            });
        }

        /// <summary>
        /// Deletes the <c>access_token</c> auth cookie.
        /// Used on logout.
        /// <para>
        /// The settings (<c>HttpOnly</c>, <c>Secure</c>, <c>SameSite</c>) must match those in <see cref="SetAuthCookie"/>, otherwise some browsers will not delete the cookie.
        /// </para>
        /// </summary>
        protected void ClearAuthCookie()
        {
            Response.Cookies.Delete("access_token", new CookieOptions
            {
                HttpOnly = true,
                Secure = true,
                SameSite = SameSiteMode.Strict
            });
        }

        /// <summary>
        /// Hides the contents of <see cref="Result{T}"/> and returns only <c>{ message = "OK" }</c> on success.
        /// <para>
        /// Used after <see cref="SetAuthCookie"/> in AuthController, so that the JWT token does not leak into the response body.
        /// </para>
        /// </summary>
        /// <typeparam name="T">The original type of the Data (e.g. <c>(string Token, DateTime Expires)</c>).</typeparam>
        /// <param name="r">The original <see cref="Result{T}"/>.</param>
        /// <returns>A <see cref="Result{T}"/> of type <c>object</c> with a generic success message, or the original error.</returns>
        protected Result<object> ResultMap<T>(Result<T> r)
        {
            if (r.IsSuccess)
                return Result<object>.Success(new { message = "OK" });

            return Result<object>.Failure(
                r.Error?.Message ?? "Unexpected error.",
                r.Error?.StatusCode ?? 500);
        }

        /// <summary>
        /// Extracts the userId of the logged-in user from the JWT claim <see cref="ClaimTypes.NameIdentifier"/>.
        /// </summary>
        /// <returns>
        /// The <c>int</c> userId on a valid claim;
        /// <c>null</c> if the claim is missing, empty, or not a valid integer.
        /// </returns>
        /// <remarks>
        /// Controllers must treat <c>null</c> as <c>401 Unauthorized</c>:
        /// <code>
        /// var userId = GetUserId();
        /// if (userId is null) return Unauthorized(new { message = "Unauthorized." });
        /// </code>
        /// </remarks>
        protected int? GetUserId()
        {
            var val = User.FindFirstValue(ClaimTypes.NameIdentifier);
            return int.TryParse(val, out var id) ? id : null;
        }
    }
}
